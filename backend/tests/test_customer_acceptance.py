def test_portal_can_accept_the_same_result_and_reject_old_versions(db, contact, bot, actor, api):
    from app.main import app
    from app.api.routers.portal import get_current_contact
    old = app.dependency_overrides.copy()
    app.dependency_overrides[get_current_contact] = lambda: contact
    try:
        t = working(db, contact); publish(db, t, bot, actor)
        path = f'/portal/tickets/{t.id}/acceptance'
        r = api.post(path, json={'resolution_message_id':t.resolution_message_id + 1,'accept':True})
        assert r.status_code == 409
        r = api.post(path, json={'resolution_message_id':t.resolution_message_id,'accept':True})
        assert r.status_code == 200, r.text
        assert r.json()['accepted_at'] and r.json()['status'] == 'closed'
        r = api.post(path, json={'resolution_message_id':t.resolution_message_id,'accept':False})
        assert r.status_code == 200 and r.json()['status'] == 'in_progress'
    finally:
        app.dependency_overrides = old


