def working(db, contact):
    t = make(db, contact)
    return tickets.transition_status(db, t, TicketStatus.IN_PROGRESS, None, notify_status=False)


def publish(db, t, bot, actor, text='Загружен прайс. Проверьте новые цены в 1С, раздел Номенклатура.', files=None):
    payload = MessageCreate(direction='outbound', channel=bot.channel, body=text, request_id=uuid4())
    customer_acceptance.submit(db, t, payload, actor, files or [])
    return payload


def deliver(db, message_id):
    job = db.query(ChannelJob).filter_by(message_id=message_id).one()
    for pending in db.query(ChannelJob).filter(ChannelJob.kind == 'outbound', ChannelJob.stream_key == job.stream_key, ChannelJob.id <= job.id, ChannelJob.state.in_(['pending', 'retry'])).order_by(ChannelJob.id).all():
        lease = queue.claim(db, 'outbound', pending.id)
        assert lease is not None
        assert queue.process_outbound(db, *lease), pending.last_error
    db.refresh(job); assert job.state == 'sent'
    return job


def test_result_delivered_with_files_and_accepted_in_bot(db, contact, bot, actor):
    t = working(db, contact)
    publish(db, t, bot, actor, files=[('result.xlsx', b'result-bytes', 'application/octet-stream')])
    assert t.status == TicketStatus.RESOLVED and not t.accepted_at
    result_id = t.resolution_message_id
    deliver(db, result_id)
    assert any('Результат работы' in x['text'] and t.display_number in x['text'] for x in bot.sent)
    assert any(x.get('file') for x in bot.sent)
    assert any(b['payload'] == f'accept:{t.id}:{result_id}' for x in bot.sent for row in (x.get('buttons') or []) for b in row)
    bot.incoming(bot.event(callback=f'accept:{t.id}:{result_id}'))
    db.refresh(t)
    assert t.status == TicketStatus.CLOSED and t.accepted_at
    accepted = t.accepted_at
    bot.incoming(bot.event(callback=f'accept:{t.id}:{result_id}'))
    db.refresh(t); assert t.accepted_at == accepted
    assert db.query(AuditLog).filter_by(entity_type='ticket', entity_id=t.id, action='customer_accepted').count() == 1


def test_closed_reply_stays_in_same_ticket_and_rework_reopens_it(db, contact, bot, actor):
    t = working(db, contact); publish(db, t, bot, actor); deliver(db, t.resolution_message_id)
    bot.incoming(bot.event(callback=f'accept:{t.id}:{t.resolution_message_id}'))
    total = db.query(Ticket).count()
    bot.incoming(bot.event(callback=f'reply:{t.id}'))
    bot.incoming(bot.event('Где проверить загрузку?'))
    db.refresh(t)
    assert t.status == TicketStatus.CLOSED and db.query(Ticket).count() == total
    assert db.query(Message).filter_by(ticket_id=t.id, body='Где проверить загрузку?').one()
    bot.incoming(bot.event(callback=f'rework:{t.id}:{t.resolution_message_id}'))
    db.refresh(t); assert t.status == TicketStatus.IN_PROGRESS and t.accepted_at is None and t.closed_at is None
    bot.incoming(bot.event('Не хватает одного артикула'))
    assert db.query(Message).filter_by(ticket_id=t.id, body='Не хватает одного артикула').one()
    assert db.query(Ticket).count() == total


