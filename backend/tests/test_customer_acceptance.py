def test_result_replay_preserves_message_files_and_internal_privacy(db, contact, bot, actor):
    t = working(db, contact)
    messages.add_message(db, t, MessageCreate(direction='internal_note', body='PRIVATE-NOTE'), author_user=actor)
    publish(db, t, bot, actor, files=[('result.pdf', b'result-pdf', 'application/pdf')]); deliver(db, t.resolution_message_id)
    count = db.query(Message).count(); bot.sent.clear()
    bot.incoming(bot.event(callback=f'result:{t.id}'))
    job = db.query(ChannelJob).filter(ChannelJob.payload['result_message_id'].as_integer() == t.resolution_message_id).one()
    # Earlier queued acknowledgements are in the same stream; deliver them first.
    for pending in db.query(ChannelJob).filter(ChannelJob.kind == 'outbound', ChannelJob.stream_key == job.stream_key, ChannelJob.id <= job.id, ChannelJob.state.in_(['pending', 'retry'])).order_by(ChannelJob.id).all():
        lease = queue.claim(db, 'outbound', pending.id)
        if not lease: break
        assert queue.process_outbound(db, *lease), pending.last_error
        db.refresh(job)
        if job.state == 'sent': break
    assert job.state == 'sent' and db.query(Message).count() == count
    assert any(x.get('file') for x in bot.sent)
    assert all('PRIVATE-NOTE' not in x['text'] for x in bot.sent)


